"""Embed the fixture photos and the desktop reference detections in a Dart file
for the on-device integration test (the test runs on a phone/emulator and can't
read the host's files). Output is generated in CI and not committed.

    python mobile/tools/gen_integration_fixtures.py
"""
import base64
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCENES = ROOT / "tests" / "fixtures" / "scenes"
GOLDEN = ROOT / "mobile" / "app" / "integration_test" / "golden" / "desktop_detections_320.json"
OUT = ROOT / "mobile" / "app" / "integration_test" / "fixtures.g.dart"

golden = json.loads(GOLDEN.read_text(encoding="utf-8"))
lines = [
    "// GENERATED by mobile/tools/gen_integration_fixtures.py - do not edit or commit.",
    "// Fixture photos: tests/fixtures/scenes (see ATTRIBUTION.md there).",
    "// ignore_for_file: lines_longer_than_80_chars",
    "const fixtureImages = <String, String>{",
]
for g in golden["images"]:
    b64 = base64.b64encode((SCENES / g["file"]).read_bytes()).decode()
    lines.append(f"  '{g['file']}': '{b64}',")
lines.append("};")
lines.append("const desktopGoldenJson = r'''" + json.dumps(golden) + "''';")
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"wrote {OUT} ({OUT.stat().st_size // 1024} KB, {len(golden['images'])} images)")
